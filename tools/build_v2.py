materi = copy.deepcopy(V1_MATERI)
for m in materi:
    m.setdefault("sumber", "Pelengkap")
    m.setdefault("sub", [])
by_id = {m["id"]: m for m in materi}
for c in SILABUS:
    kat, ring = INFO[c["id"]]
    if c["id"] in by_id:
        # Mata kuliah v1 yang sama dengan silabus: pakai nama resmi, simpan nama lama sebagai alias, tambah sub-materi.
        m = by_id[c["id"]]
        if m["nama"] != c["nama"]:
            m["alias"] = m["nama"]
            m["nama"] = c["nama"]
        m["semester"] = c["semester"]
        m["semesterPasti"] = c["semesterPasti"]
        m["sumber"] = "Silabus ITS"
        m["sub"] = c["sub"]
        if c["pengantar"]:
            m["pengantar"] = c["pengantar"]
        continue
    materi.append({
        "id": c["id"], "nama": c["nama"], "semester": c["semester"], "semesterPasti": c["semesterPasti"],
        "kategori": kat, "sumber": "Silabus ITS", "ringkasan": ring, "pengantar": c["pengantar"],
        "sub": c["sub"], "topik": [], "referensi": [], "catatan": "",
    })
ids = {m["id"] for m in materi}
subs_of = {m["id"]: {s["no"] for s in m.get("sub", [])} for m in materi}


def K(m, t, blok, peran, sub=()):
    assert m in ids, m
    sub = [str(s) for s in sub]
    for s in sub:
        assert s in subs_of[m], (m, s)
    return {"materi": m, "tingkat": t, "blok": list(blok), "peran": peran, "sub": sub}


